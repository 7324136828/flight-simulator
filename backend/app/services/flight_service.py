"""Flight logbook and telemetry export service."""

from __future__ import annotations

import csv
import json
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ..database import Database
from ..utils.temp_manager import TempManager


class FlightService:
    """Manages flight logs, telemetry records, and ZIP export packages."""

    def __init__(self, db: Database, temp_manager: TempManager | None = None) -> None:
        self.db = db
        self.temp_manager = temp_manager or TempManager()

    def record_flight(self, data: dict[str, Any]) -> dict[str, Any]:
        flight_id = str(uuid.uuid4())
        return self.db.create_flight(flight_id, data)

    def get_flight(self, flight_id: str) -> dict[str, Any] | None:
        return self.db.get_flight(flight_id)

    def list_flights(self) -> list[dict[str, Any]]:
        return self.db.list_flights()

    def delete_flight(self, flight_id: str) -> bool:
        return self.db.delete_flight(flight_id)

    def export_flight_zip(self, flight_id: str) -> Path:
        """Packages flight report, telemetry JSON, CSV track, and KML into an isolated ZIP."""
        flight = self.get_flight(flight_id)
        if not flight:
            raise KeyError(f"Flight {flight_id} not found")

        job_id = f"export_{flight_id}"
        env = self.temp_manager.create_job_env(job_id)
        outputs_dir = env["outputs"]

        # 1. Generate flight summary markdown
        summary_md = outputs_dir / "flight_summary.md"
        content_md = f"""# Flight Summary Report

- **Flight ID**: `{flight['id']}`
- **Date & Time**: {flight['created_at']}
- **Scenery Area**: {flight['map_label']} (`{flight['map_id']}`)
- **Runway**: `{flight['runway_id']}` (Heading: {flight.get('runway_heading', 0):.1f}°)
- **Flight Duration**: {flight['duration_seconds']:.1f} seconds
- **Max Airspeed**: {flight['max_speed_knots']:.1f} knots
- **Max Altitude**: {flight['max_altitude_feet']:.1f} feet
- **Landing Status**: **{flight['landing_status'].upper()}**
- **Touchdown Vertical Speed**: {flight.get('touchdown_vertical_speed_fpm') or 'N/A'} fpm
- **Centerline Deviation**: {flight.get('centerline_offset_feet') or 'N/A'} feet
- **Pilot Rating**: {'★' * flight.get('rating_stars', 0)}{'☆' * (5 - flight.get('rating_stars', 0))}

---
Generated by Flight Simulator Production System
"""
        summary_md.write_text(content_md, encoding="utf-8")

        # 2. Telemetry JSON
        telemetry_file = outputs_dir / "telemetry.json"
        telemetry_data = flight.get("telemetry", [])
        with open(telemetry_file, "w", encoding="utf-8") as f:
            json.dump(telemetry_data, f, indent=2)

        # 3. Track CSV
        csv_file = outputs_dir / "flight_track.csv"
        with open(csv_file, "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow([
                "time_sec", "x_m", "y_m", "z_m",
                "pitch_deg", "roll_deg", "heading_deg",
                "airspeed_kts", "altitude_ft", "vspeed_fpm",
                "throttle", "gear", "flaps"
            ])
            for pt in telemetry_data:
                writer.writerow([
                    pt.get("time", 0.0),
                    pt.get("x", 0.0),
                    pt.get("y", 0.0),
                    pt.get("z", 0.0),
                    pt.get("pitch", 0.0),
                    pt.get("roll", 0.0),
                    pt.get("heading", 0.0),
                    pt.get("airspeed_knots", 0.0),
                    pt.get("altitude_feet", 0.0),
                    pt.get("vertical_speed_fpm", 0.0),
                    pt.get("throttle", 0.0),
                    pt.get("gear", True),
                    pt.get("flaps", False),
                ])

        # 4. KML file for 3D trajectory mapping
        kml_file = outputs_dir / "flight_path.kml"
        coordinates = []
        for pt in telemetry_data:
            # Approximate local projection to lat/lon offsets
            x = pt.get("x", 0.0)
            z = pt.get("z", 0.0)
            alt = pt.get("y", 0.0)
            # Default Meigs Field origin: -87.608, 41.860
            lon = -87.608 + (x / 82000.0)
            lat = 41.860 + (z / 111000.0)
            coordinates.append(f"{lon:.6f},{lat:.6f},{alt:.1f}")

        coords_str = " ".join(coordinates)
        kml_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>Flight {flight['id']}</name>
    <description>Recorded flight path in {flight['map_label']}</description>
    <Placemark>
      <name>Trajectory</name>
      <LineString>
        <extrude>1</extrude>
        <tessellate>1</tessellate>
        <altitudeMode>relativeToGround</altitudeMode>
        <coordinates>
          {coords_str}
        </coordinates>
      </LineString>
    </Placemark>
  </Document>
</kml>
"""
        kml_file.write_text(kml_content, encoding="utf-8")

        # Package outputs to zip
        zip_path = self.temp_manager.package_outputs_to_zip(
            job_id, archive_name=f"flight_{flight_id[:8]}_export.zip"
        )
        return zip_path

